export function L(key, vars = {}) {
  let v = DICTS[lang][key] ?? en[key];
  if (v == null) return key;
  if (typeof v === 'object') {
    const form = pluralForm(vars.n ?? 0, lang);
    v = v[form] ?? v.other ?? v.many ?? v.one;
  }
  return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}
